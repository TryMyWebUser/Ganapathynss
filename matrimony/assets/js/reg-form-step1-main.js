function ValidateEmail(Email) {
    var atCharPresent = false;
    var dotPresent = false;
    for (var Idx = 0; Idx < Email.length; Idx++) {
        if (Email.charAt(Idx) == '@')
            atCharPresent = true;
        if (Email.charAt(Idx) == '.')
            dotPresent = true;
    }
    if (!atCharPresent || !dotPresent)
        return false;
    return true;
}

